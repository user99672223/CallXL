#!/usr/bin/env python3
"""design/tokens.json -> apps/ios/CallXL/Theme/Tokens.swift (shared design tokens, §9).

Usage: packaging/ios/gen-tokens.py [--check]
--check exits 1 when the committed Tokens.swift is out of date (CI).
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "design" / "tokens.json"
DST = ROOT / "apps" / "ios" / "CallXL" / "Theme" / "Tokens.swift"


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def rgba(hexstr: str) -> str:
    h = hexstr.lstrip("#")
    if len(h) == 6:
        h += "FF"
    r, g, b, a = (int(h[i : i + 2], 16) / 255 for i in range(0, 8, 2))
    return f"RGBA(r: {r:.4f}, g: {g:.4f}, b: {b:.4f}, a: {a:.4f})"


def render(t: dict) -> str:
    out = [
        "// Generated by packaging/ios/gen-tokens.py from design/tokens.json. Do not edit.",
        "",
        "import CoreGraphics",
        "",
        "struct RGBA: Equatable {",
        "    let r: Double",
        "    let g: Double",
        "    let b: Double",
        "    let a: Double",
        "}",
        "",
        "struct Palette: Equatable {",
    ]
    keys = list(t["color"]["dark"].keys())
    out += [f"    let {camel(k)}: RGBA" for k in keys]
    out += ["}", "", "enum Tokens {"]
    for scheme in ("dark", "light"):
        out.append(f"    static let {scheme} = Palette(")
        cols = t["color"][scheme]
        args = [f"        {camel(k)}: {rgba(cols[k])}" for k in keys]
        out.append(",\n".join(args))
        out.append("    )")
        out.append("")
    for group in ("space", "radius", "size"):
        if group not in t:
            continue
        out.append(f"    enum {group.capitalize()} {{")
        for k, v in t[group].items():
            out.append(f"        static let {camel(k)}: CGFloat = {v}")
        out.append("    }")
        out.append("")
    out.append("    enum Motion {")
    for k, v in t["motion"].items():
        out.append(f"        /// {v} ms")
        out.append(f"        static let {camel(k)}: Double = {v / 1000:.3f}")
    out.append("    }")
    out.append("")
    out.append("    struct TypeStyle: Equatable {")
    out.append("        let size: CGFloat")
    out.append("        let weight: Int")
    out.append("    }")
    out.append("")
    out.append("    enum Typography {")
    for k, v in t["type"].items():
        out.append(f"        static let {camel(k)} = TypeStyle(size: {v['size']}, weight: {v['weight']})")
    out.append("    }")
    family = t.get("font", {}).get("family", "")
    out.append("")
    out.append(f'    static let fontFamily = "{family}"')
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    text = render(json.loads(SRC.read_text()))
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text() != text:
            print(f"{DST} is out of date; run packaging/ios/gen-tokens.py", file=sys.stderr)
            return 1
        return 0
    DST.write_text(text)
    print(f"wrote {DST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
