//! Generates `@tokens` (Slint globals) from `design/tokens.json`, the single source of
//! truth shared with the iOS app (CLAUDE.md §9), then compiles the `.slint` UI to Rust.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

fn ident(k: &str) -> String {
    k.replace('_', "-")
}

fn color(v: &Value, ctx: &str) -> String {
    let s = v.as_str().unwrap_or_else(|| panic!("{ctx}: colour must be a string"));
    let hex = s.strip_prefix('#').unwrap_or_else(|| panic!("{ctx}: colour must start with #"));
    assert!(
        matches!(hex.len(), 6 | 8) && hex.chars().all(|c| c.is_ascii_hexdigit()),
        "{ctx}: colour must be #RRGGBB or #RRGGBBAA, got {s}"
    );
    format!("#{hex}")
}

fn num(v: &Value, ctx: &str) -> f64 {
    v.as_f64().unwrap_or_else(|| panic!("{ctx}: must be a number"))
}

fn obj<'a>(v: &'a Value, path: &str) -> &'a Map<String, Value> {
    path.split('.')
        .try_fold(v, |v, k| v.get(k))
        .and_then(Value::as_object)
        .unwrap_or_else(|| panic!("tokens.json: missing object '{path}'"))
}

/// The Slint source for `@tokens`.
fn generate(tokens: &Value) -> String {
    let mut out = String::from("// Generated by apps/desktop/build.rs from design/tokens.json. Do not edit.\n\n");

    // Colours: one global; `dark` selects the variant (dark is the default theme).
    let dark = obj(tokens, "color.dark");
    let light = obj(tokens, "color.light");
    out.push_str("export global Colors {\n    in-out property <bool> dark: true;\n");
    for (k, dv) in dark.iter().collect::<BTreeMap<_, _>>() {
        let lv = light.get(k).unwrap_or_else(|| panic!("tokens.json: color.light.{k} missing"));
        let _ = writeln!(
            out,
            "    out property <color> {}: dark ? {} : {};",
            ident(k),
            color(dv, &format!("color.dark.{k}")),
            color(lv, &format!("color.light.{k}"))
        );
    }
    for k in light.keys() {
        assert!(dark.contains_key(k), "tokens.json: color.dark.{k} missing");
    }
    out.push_str("}\n\n");

    for (global, key, unit, ty) in [
        ("Space", "space", "px", "length"),
        ("Radius", "radius", "px", "length"),
        ("Motion", "motion", "ms", "duration"),
        ("Size", "size", "px", "length"),
    ] {
        let _ = writeln!(out, "export global {global} {{");
        for (k, v) in obj(tokens, key).iter().collect::<BTreeMap<_, _>>() {
            let _ = writeln!(out, "    out property <{ty}> {}: {}{unit};", ident(k), num(v, &format!("{key}.{k}")));
        }
        out.push_str("}\n\n");
    }

    out.push_str("export global Type {\n");
    for (k, v) in obj(tokens, "type").iter().collect::<BTreeMap<_, _>>() {
        let ctx = format!("type.{k}");
        let _ = writeln!(out, "    out property <length> {}-size: {}px;", ident(k), num(&v["size"], &ctx));
        let _ = writeln!(out, "    out property <int> {}-weight: {};", ident(k), num(&v["weight"], &ctx));
    }
    let family = tokens["font"]["family"].as_str().unwrap_or("Inter");
    let _ = writeln!(out, "    out property <string> family: \"{family}\";");
    out.push_str("}\n");
    out
}

fn slashes(p: &Path) -> String {
    let s = p.to_string_lossy().replace('\\', "/");
    // canonicalize() on Windows yields a verbatim `\\?\C:\…` path.
    s.strip_prefix("//?/").map(str::to_string).unwrap_or(s)
}

fn write_if_changed(path: &Path, content: &str) {
    if std::fs::read_to_string(path).ok().as_deref() != Some(content) {
        std::fs::write(path, content).expect("write generated tokens.slint");
    }
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let design = manifest.join("../../design").canonicalize().expect("design/ directory");
    let tokens_path = design.join("tokens.json");
    println!("cargo:rerun-if-changed={}", tokens_path.display());
    let tokens: Value = serde_json::from_str(&std::fs::read_to_string(&tokens_path).expect("read design/tokens.json"))
        .expect("design/tokens.json is not valid JSON");

    // Embedded fonts (Latin subset of Inter, OFL): identical text on Windows and Linux.
    let mut slint = String::new();
    for f in tokens["font"]["files"].as_array().into_iter().flatten().filter_map(Value::as_str) {
        let p = design.join(f).canonicalize().unwrap_or_else(|_| panic!("font {f} missing"));
        println!("cargo:rerun-if-changed={}", p.display());
        let _ = writeln!(slint, "import \"{}\";", slashes(&p));
    }
    slint.push_str(&generate(&tokens));
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let tokens_slint = out_dir.join("tokens.slint");
    write_if_changed(&tokens_slint, &slint);

    let config = slint_build::CompilerConfiguration::new()
        .with_style("fluent".into())
        .with_library_paths(
            [("tokens".to_string(), tokens_slint), ("icons".to_string(), design.join("icons"))].into_iter().collect(),
        );
    slint_build::compile_with_config("ui/app.slint", config).expect("Slint UI failed to compile");

    // Windows: embed the app icon into callxl.exe (host == target in CI).
    #[cfg(windows)]
    {
        let ico = design.join("icons/callxl.ico");
        println!("cargo:rerun-if-changed={}", ico.display());
        let rc = out_dir.join("callxl.rc");
        write_if_changed(&rc, &format!("1 ICON \"{}\"\n", slashes(&ico)));
        embed_resource::compile(&rc, embed_resource::NONE).manifest_optional().expect("embed icon resource");
    }
}
